"use client";

import { useSearchParams } from "next/navigation";
import { useRef, useState } from "react";
import { AlertCircle, Cpu, Eraser, FileText, Loader2, Minimize2, PenLine, Sparkles, Wand2 } from "lucide-react";
import { Button } from "@/components/ui/button";
import { CopyButton } from "@/components/ui/copy-button";
import { ConfirmDialog } from "@/components/ui/dialog";
import { Label, Select, Textarea } from "@/components/ui/form";
import { Badge, Callout } from "@/components/ui/misc";
import { CONTENT_TYPES, TONES, type ContentType, type Tone, type WritingAction } from "@/lib/tools/local-writer";
import { cn } from "@/lib/utils";
import { usePersistentState } from "./use-persistent-state";

type State = { type: ContentType; tone: Tone; input: string; output: string };

const PLACEHOLDERS: Record<ContentType, string> = {
  email: "e.g. thank Priya for the intro call · share the proposal by Friday · ask for a 30-min review slot next week",
  social: "e.g. launched our new budget template · free for students · link in bio",
  linkedin: "e.g. finished the client dashboard project · cut reporting time from 2 days to 3 hours · thank the team",
  summary: "Paste meeting notes, an article or a long message to summarise…",
  blog: "e.g. why weekly reviews matter · 20 minutes on Friday · three outcomes for next week",
  rewrite: "Paste the text you want rewritten…",
};

const MAX_INPUT = 6000;

function countWords(s: string) {
  return s.trim() ? s.trim().split(/\s+/).length : 0;
}

export function WritingWorkspace({ aiEnabled }: { aiEnabled: boolean }) {
  const params = useSearchParams();
  const presetType = CONTENT_TYPES.find((t) => t.key === params.get("type"))?.key;
  const presetTone = TONES.find((t) => t.key === params.get("tone"))?.key;
  // URL presets (e.g. from the Email Reply Assistant) win over stored settings.
  const [state, setState] = usePersistentState<State>(
    "lifeos.tool.writing",
    { type: "email", tone: "professional", input: "", output: "" },
    { ...(presetType && { type: presetType }), ...(presetTone && { tone: presetTone }) },
  );

  const [pending, setPending] = useState<WritingAction | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [mode, setMode] = useState<"ai" | "local" | null>(null);
  const outputRef = useRef<HTMLTextAreaElement>(null);

  const set = <K extends keyof State>(k: K, v: State[K]) => setState((s) => ({ ...s, [k]: v }));

  async function run(action: WritingAction) {
    setError(null);
    if (action === "generate" && state.input.trim().length < 3) {
      setError("Add a few words of notes first.");
      return;
    }
    if (action !== "generate" && !state.output.trim()) {
      setError("Generate a draft first, then refine it.");
      return;
    }
    setPending(action);
    try {
      const res = await fetch("/api/tools/writing", {
        method: "POST",
        headers: { "content-type": "application/json" },
        body: JSON.stringify({ action, type: state.type, tone: state.tone, input: state.input, draft: action === "generate" ? undefined : state.output }),
      });
      const data = await res.json().catch(() => ({}));
      if (!res.ok) {
        setError(data.error ?? "Something went wrong. Please try again.");
        return;
      }
      setMode(data.mode);
      if (!data.output) {
        setError("Couldn't build a draft from those notes. Try adding a little more detail.");
        return;
      }
      set("output", data.output);
      requestAnimationFrame(() => outputRef.current?.focus());
    } catch {
      setError("You appear to be offline. Check your connection and try again.");
    } finally {
      setPending(null);
    }
  }

  const words = countWords(state.output);
  const busy = pending !== null;

  return (
    <div className="space-y-5">
      {aiEnabled ? (
        <Callout tone="accent" icon={Sparkles} title="Connected to Claude">
          Drafts are generated by an AI model on our servers. Review everything before you send it — AI can make mistakes.
        </Callout>
      ) : (
        <Callout tone="warning" icon={Cpu} title="Local demo mode — no AI service connected">
          No AI provider is configured, so drafts are produced by a simple rule-based formatter that restructures your own notes. It
          won&apos;t add new ideas. Set <code className="font-mono text-[12px]">ANTHROPIC_API_KEY</code> on the server to enable AI drafting.
        </Callout>
      )}

      <div className="grid grid-cols-1 gap-5 lg:grid-cols-[minmax(0,5fr)_minmax(0,6fr)]">
        {/* Input */}
        <section aria-labelledby="writing-input" className="rounded-[var(--radius-panel)] border border-line bg-surface p-5">
          <h2 id="writing-input" className="text-[15px] font-semibold tracking-[-0.015em]">
            What do you want to write?
          </h2>
          <div className="mt-4">
            <p id="type-label" className="text-[13px] font-medium">
              Format
            </p>
            <div className="mt-2 flex flex-wrap gap-1.5" role="radiogroup" aria-labelledby="type-label">
              {CONTENT_TYPES.map((t) => (
                <button
                  key={t.key}
                  type="button"
                  role="radio"
                  aria-checked={state.type === t.key}
                  onClick={() => set("type", t.key)}
                  className={cn(
                    "h-8 rounded-full border px-3 text-[13px] transition-colors",
                    state.type === t.key ? "border-ink bg-ink text-white" : "border-line text-ink-2 hover:border-line-strong hover:text-ink",
                  )}
                >
                  {t.label}
                </button>
              ))}
            </div>
          </div>
          <div className="mt-4 flex flex-col gap-1.5">
            <Label htmlFor="tone">Tone</Label>
            <Select id="tone" value={state.tone} onChange={(e) => set("tone", e.target.value as Tone)}>
              {TONES.map((t) => (
                <option key={t.key} value={t.key}>
                  {t.label}
                </option>
              ))}
            </Select>
          </div>
          <div className="mt-4 flex flex-col gap-1.5">
            <div className="flex items-baseline justify-between">
              <Label htmlFor="notes">Your notes</Label>
              <span className={cn("text-xs tabular-nums", state.input.length > MAX_INPUT ? "text-danger" : "text-ink-3")}>
                {state.input.length.toLocaleString("en-IN")} / {MAX_INPUT.toLocaleString("en-IN")}
              </span>
            </div>
            <Textarea
              id="notes"
              value={state.input}
              onChange={(e) => set("input", e.target.value)}
              placeholder={PLACEHOLDERS[state.type]}
              rows={9}
              maxLength={MAX_INPUT}
              aria-describedby="notes-hint"
              onKeyDown={(e) => {
                if ((e.metaKey || e.ctrlKey) && e.key === "Enter") run("generate");
              }}
            />
            <p id="notes-hint" className="text-[12.5px] text-ink-3">
              Bullet points or rough sentences work best. Press ⌘/Ctrl + Enter to generate.
            </p>
          </div>
          <div className="mt-5 flex items-center gap-2">
            <Button onClick={() => run("generate")} disabled={busy} className="flex-1 sm:flex-none">
              {pending === "generate" ? <Loader2 className="animate-spin" /> : <Wand2 />}
              {pending === "generate" ? "Generating…" : "Generate draft"}
            </Button>
            <ConfirmDialog
              trigger={
                <Button variant="ghost" disabled={busy || (!state.input && !state.output)}>
                  <Eraser /> Clear
                </Button>
              }
              title="Clear notes and draft?"
              description="This removes your notes and the current draft from this browser. It can't be undone."
              confirmLabel="Clear everything"
              onConfirm={() => {
                setState((s) => ({ ...s, input: "", output: "" }));
                setMode(null);
                setError(null);
              }}
            />
          </div>
        </section>

        {/* Output */}
        <section aria-labelledby="writing-output" className="flex flex-col rounded-[var(--radius-panel)] border border-line bg-surface">
          <div className="flex flex-wrap items-center justify-between gap-2 border-b border-line px-5 py-3">
            <div className="flex items-center gap-2">
              <h2 id="writing-output" className="text-[15px] font-semibold tracking-[-0.015em]">
                Draft
              </h2>
              {mode === "ai" && <Badge tone="accent" icon={Sparkles}>AI draft</Badge>}
              {mode === "local" && <Badge tone="warning" icon={Cpu}>Local formatter</Badge>}
            </div>
            <CopyButton text={state.output} size="sm" toastMessage="Draft copied to clipboard" />
          </div>
          <label htmlFor="output" className="sr-only">
            Draft (editable)
          </label>
          <textarea
            id="output"
            ref={outputRef}
            value={state.output}
            onChange={(e) => set("output", e.target.value)}
            placeholder="Your draft will appear here. You can edit it directly."
            className="min-h-[320px] flex-1 resize-y bg-transparent px-5 py-4 text-[14.5px] leading-relaxed text-ink outline-none placeholder:text-ink-3"
            aria-busy={busy}
          />
          {error && (
            <p role="alert" className="mx-5 mb-3 flex items-start gap-2 rounded-[10px] bg-danger-soft px-3 py-2 text-[13px] text-danger">
              <AlertCircle className="mt-0.5 size-3.5 shrink-0" /> {error}
            </p>
          )}
          <div className="flex flex-wrap items-center gap-2 border-t border-line px-5 py-3">
            <Button variant="secondary" size="sm" onClick={() => run("improve")} disabled={busy || !state.output}>
              {pending === "improve" ? <Loader2 className="animate-spin" /> : <PenLine />} Improve
            </Button>
            <Button variant="secondary" size="sm" onClick={() => run("shorter")} disabled={busy || !state.output}>
              {pending === "shorter" ? <Loader2 className="animate-spin" /> : <Minimize2 />} Shorter
            </Button>
            <Button variant="secondary" size="sm" onClick={() => run("formal")} disabled={busy || !state.output}>
              {pending === "formal" ? <Loader2 className="animate-spin" /> : <FileText />} More formal
            </Button>
            <span className="ml-auto text-[12.5px] tabular-nums text-ink-3" aria-live="polite">
              {words} word{words === 1 ? "" : "s"}
            </span>
          </div>
        </section>
      </div>
    </div>
  );
}
